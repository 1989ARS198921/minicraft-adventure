// ============================================================
//  📮 ШИНА СОБЫТИЙ — «почта» игры
//  Модули не звонят друг другу напрямую, а оставляют объявления:
//  «блок сломан!», «игрок прыгнул!», «мир изменился!».
//  Кто подписался — тот и reacts (квесты, сохранение...).
//  Так модули не зависят друг от друга и их легко менять.
// ============================================================

const listeners = {}; // событие -> список подписчиков

// Подписаться на событие
export function on(event, fn) {
  (listeners[event] ||= []).push(fn);
}

// Объявить событие (все подписчики получат аргументы)
export function emit(event, ...args) {
  (listeners[event] || []).forEach(fn => fn(...args));
}
