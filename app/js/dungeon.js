// ============================================================
//  🕯️ ПОДЗЕМЕЛЬЕ — ПЕЩЕРА КОРОЛЯ ГОБЛИНОВ
//  Настоящая пещера глубоко под холмом: по открытой лестнице
//  ныряешь в тёмный тоннель, проходишь под аркой — и попадаешь
//  в сводчатый зал! Кирпичные своды держат потолок, в стенах
//  блестят руды, факелы горят, а на троне сидит ОГРОМНЫЙ
//  Король Гоблинов. Сверху пещеру закрывает целый холм —
//  снаружи видны только ворота да лестница, уходящая вниз.
//
//  КАК ЭТО РАБОТАЕТ? Наша «ходилка» умеет в стены и потолки:
//  герой ищет землю только НИЖЕ себя (с «потолком поиска»),
//  поэтому в пещере стоит на полу, а не вскакивает на крышу!
// ============================================================

import { emit } from './bus.js';

// Границы зала и ключевые точки
export const DUNGEON = {
  x0: -72, x1: -62,   // зал: 10 блоков с запада на восток
  z0: 49,  z1: 62,    //      14 блоков с севера на юг
  floorY: -4,         // пол (стоим на -3), воздух до y=1, потолок y=2
  bossX: -70.5, bossZ: 55.5 // 👑 трон у западной стены (НЕ в колонне спинки!)
};

// Факелы пещеры: на воротах у входа и в зале у стен и трона
export const DUNGEON_TORCHES = [
  [-61, 6, 49], [-61, 6, 52],   // 🔥 на кирпичных воротах у входа
  [-70, -3, 49], [-70, -3, 62], // 🔥 в зале у северной и южной стен
  [-64, -3, 49], [-64, -3, 62],
  [-71, -3, 53], [-71, -3, 58]  // 🔥 у самого трона — жутковато!
];

// Поставить/убрать блок, если клетка попадает в этот чанк
function put(data, x0, z0, x, y, z, type) {
  if (x >= x0 && x < x0 + 16 && z >= z0 && z < z0 + 16) {
    const k = x + ',' + y + ',' + z;
    if (type) data.set(k, type); else data.delete(k);
  }
}

// Ступенька лестницы: сплошной столбик до высоты topY, выше — воздух.
// ceilY — где заканчивается воздух (по умолчанию 40 — до самого неба).
// У крытых ступенек тоннеля воздух только до потолка (y = 1)!
function stampStep(data, x0, z0, x, z, topY, ceilY = 40) {
  for (let y = topY + 1; y <= ceilY; y++) put(data, x0, z0, x, y, z, null);
  for (let y = DUNGEON.floorY; y <= topY; y++) put(data, x0, z0, x, y, z, 'stone');
}

// Впечатать пещеру в чанк (вызывается из генератора мира)
export function stampDungeon(data, cx, cz) {
  const x0 = cx * 16, z0 = cz * 16;
  const D = DUNGEON;
  // Чанк вообще не пересекается с пещерой и площадкой перед ней? Ничего не делаем
  if (x0 + 15 < D.x0 - 4 || x0 > D.x1 + 6 || z0 + 15 < D.z0 - 2 || z0 > D.z1 + 2) return;

  // --- ПЛОЩАДКА ПЕРЕД ВХОДОМ (с востока): ровная травка ---
  for (let x = D.x1 + 1; x <= D.x1 + 6; x++)
    for (let z = 48; z <= 53; z++) {
      for (let y = 3; y <= 40; y++) put(data, x0, z0, x, y, z, null);
      for (let y = D.floorY; y <= 2; y++)
        put(data, x0, z0, x, y, z, y === 2 ? 'grass' : y <= 0 ? 'stone' : 'dirt');
    }

  // --- ЛЕСТНИЦА: 7 ступенек вниз с востока (z = 50..51) ---
  // Ступенька i на x = x1 - i: стоим на высоте 3 - i (от травы до пола).
  // Первые три — под открытым небом, остальные ныряют под свод тоннеля!
  for (let i = 0; i <= 6; i++)
    for (let z = 50; z <= 51; z++)
      stampStep(data, x0, z0, D.x1 - i, z, 2 - i, i <= 2 ? 40 : 1);

  // --- ЗАЛ: выкапываем комнату, но ПОТОЛОК (y=2) ОСТАВЛЯЕМ! ---
  // Сверху — обычный холм с травой, пещера спрятана под ним.
  for (let x = D.x0; x <= D.x1 - 1; x++)
    for (let z = D.z0; z <= D.z1; z++) {
      const isStair = (z === 50 || z === 51) && x >= D.x0 + 4; // лестницу не трогаем!
      if (isStair) continue;
      for (let y = D.floorY + 1; y <= 1; y++) put(data, x0, z0, x, y, z, null); // воздух зала
      put(data, x0, z0, x, D.floorY, z, 'stone'); // каменный пол
    }

  // --- 🪨 СВОД-ПОТОЛОК: каменная крыша над всей пещерой! ---
  // Над залом плескалось озерцо — заменяем воду на камень:
  // сверху остаётся плоская каменная площадка, будто руины.
  for (let x = D.x0 - 1; x <= D.x1; x++)
    for (let z = D.z0 - 1; z <= D.z1 + 1; z++)
      put(data, x0, z0, x, 2, z, 'stone');

  // --- 🏛️ СВОДЫ! Три кирпичные арки держат потолок ---
  // Пилястры у стен от пола до потолка + перемычка наверху — как в замке!
  for (const ax of [-69, -66, -63])
    for (let z = 52; z <= 62; z++) {
      if (z === 52 || z === 62) // пилястры у стен: пять блоков вверх
        for (let y = D.floorY + 1; y <= 1; y++) put(data, x0, z0, ax, y, z, 'brick');
      else // перемычка свода — высоко, под ней и Король пройдёт
        put(data, x0, z0, ax, 1, z, 'brick');
    }

  // --- 🚪 АРКА-ДВЕРЬ: там, где лестница входит в зал ---
  for (const z of [49, 52])
    for (let y = D.floorY + 1; y <= 0; y++) put(data, x0, z0, D.x0 + 4, y, z, 'brick');
  for (const z of [50, 51]) put(data, x0, z0, D.x0 + 4, 1, z, 'brick'); // перемычка

  // --- 👑 ТРОН: широкий кирпичный помост у западной стены + спинка ---
  // Король стоит на краю помоста (x = -70.5) — колонка -70,
  // а спинка трона в колонке -72: не мешает ему сходить с трона!
  for (let x = D.x0; x <= D.x0 + 2; x++)
    for (let z = 54; z <= 57; z++)
      put(data, x0, z0, x, D.floorY + 1, z, 'brick'); // помост, стоим на -2
  for (let z = 54; z <= 57; z++)
    for (let y = D.floorY + 2; y <= 0; y++)
      put(data, x0, z0, D.x0, y, z, 'brick'); // высокая спинка трона

  // --- 🏰 ВОРОТА У ВХОДА: два столба и арка над лестницей ---
  for (const z of [49, 52])
    for (let y = 3; y <= 5; y++) put(data, x0, z0, D.x1 + 1, y, z, 'brick');
  for (const z of [50, 51]) put(data, x0, z0, D.x1 + 1, 5, z, 'brick'); // арка ворот

  // --- 💰 СОКРОВИЩА В СТЕНАХ! Руды блестят из камня ---
  const veins = [
    // западная стена (за троном и рядом)
    [D.x0 - 1, -2, 51, 'goldOre'], [D.x0 - 1, -1, 60, 'diamondOre'], [D.x0 - 1, 0, 52, 'goldOre'],
    // южная стена
    [-70, -2, D.z1 + 1, 'goldOre'], [-66, -1, D.z1 + 1, 'diamondOre'], [-64, -2, D.z1 + 1, 'coalOre'],
    // северная стена
    [-65, -2, D.z0 - 1, 'goldOre'], [-70, -1, D.z0 - 1, 'coalOre'],
    // восточная стена (южнее лестницы)
    [D.x1, -2, 56, 'diamondOre'], [D.x1, -1, 60, 'goldOre'],
    // алмазы прямо в полу у трона — награда смелым!
    [-69, D.floorY, 58, 'diamondOre'], [-65, D.floorY, 53, 'goldOre'], [-70, D.floorY, 60, 'goldOre']
  ];
  for (const [x, y, z, t] of veins) put(data, x0, z0, x, y, z, t);
}

// ---------- 🕯️ КАЖДЫЙ КАДР: «ура, мы нашли подземелье!» ----------
let G = null;
let announced = false; // кричим «ура» только один раз за заход

export function initDungeon(gameContext) { G = gameContext; }

export function updateDungeon() {
  if (announced) return;
  const p = G.player;
  const D = DUNGEON;
  // Игрок спустился под землю на лестнице или в зале?
  if (p.feet <= -2 && p.x >= D.x0 - 1 && p.x <= D.x1 + 6 && p.z >= D.z0 - 2 && p.z <= D.z1 + 2) {
    announced = true;
    emit('dungeon'); // квест «Найди каменоломню»
  }
}
